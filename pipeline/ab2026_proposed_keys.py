"""Write or check the AB2026 harvest's PROPOSED_KEYS.md.

A row whose scope matches no registered measure has `measure_key: null` and
names a proposed key in `conditions.proposed_measure_key` (README rule 2).
Tranche 2 of #230 registers each proposed key, or folds it into a registered
one, before the ingest runs. This lists every proposed key once, with the
families and producers that use it and its row count, so that work starts
from a complete list. Each family's NOTES.md gives the scope of every key its
rows use; the contract checks that.

    python pipeline/ab2026_proposed_keys.py sources/harvest-uk-ab2026-2026-10-29
    python pipeline/ab2026_proposed_keys.py sources/harvest-uk-ab2026-2026-10-29 --check
"""

import argparse
import sys
from collections import defaultdict
from pathlib import Path

from pipeline.ab2026_harvest_contract import read_rows

HEADER = """\
# Proposed measure keys in the AB2026 harvest

Generated by `pipeline/ab2026_proposed_keys.py` from the staged families; don't edit by hand.

A row whose scope matches no registered measure has `measure_key: null` and names one of these keys in `conditions.proposed_measure_key` (README rule 2). Each family's NOTES.md gives the key's scope as Table 6.1 lines or the producer's own words. Tranche 2 registers each key in `data/uk/ab2026_measures.json`, or folds it into a registered key, before the ingest.
"""


def inventory(harvest):
    """{proposed key: {"rows": n, "families": set, "sources": set}}."""
    out = defaultdict(lambda: {"rows": 0, "families": set(), "sources": set()})
    for fam in sorted(Path(harvest).iterdir()):
        if not (fam / "claims_staged.jsonl.gz").exists():
            continue
        for r in read_rows(fam):
            pk = r["conditions"].get("proposed_measure_key")
            if pk:
                out[pk]["rows"] += 1
                out[pk]["families"].add(fam.name)
                out[pk]["sources"].add(r["source"])
    return dict(out)


def render(harvest):
    inv = inventory(harvest)
    packages = sum(1 for k in inv if k.startswith("ab2026__"))
    rows = sum(v["rows"] for v in inv.values())
    options = len(inv) - packages
    tally = f"{len(inv)} proposed keys ({packages} packages, {options} options)"
    lines = [HEADER, f"{tally} on {rows} rows.", ""]
    if inv:
        lines += [
            "| proposed key | rows | families | producers |",
            "|---|--:|---|---|",
        ]
        for k in sorted(inv):
            v = inv[k]
            lines.append(
                f"| `{k}` | {v['rows']} | {', '.join(sorted(v['families']))} "
                f"| {', '.join(sorted(v['sources']))} |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("harvest")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    path = Path(args.harvest) / "PROPOSED_KEYS.md"
    text = render(args.harvest)
    if args.check:
        if not path.exists() or path.read_text() != text:
            print("PROPOSED_KEYS.md is stale")
            return 1
        print("PROPOSED_KEYS.md matches the families")
        return 0
    path.write_text(text)
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
