"""The decision on each AB2026 measure key a family proposed (#230).

A staged row whose scope matched no registered measure had
`measure_key: null` and a proposed key in `conditions.proposed_measure_key`
(harvest README rule 2). This module records, for each of the 86 proposed
keys, whether we register it in `data/uk/ab2026_measures.json` or fold it into
a registered key, the scope the family's NOTES.md gives it, and the registry
verdict. `pipeline/build_ab2026_registry.py` builds an entry from each
registered key, and `pipeline/apply_ab2026_key_decisions.py` moves each row's
key into `measure_key`, where AB2025's rows name theirs, and writes
`KEY_DECISIONS.md`.

Two producers' packages share a key only if their scopes match line for line
(rule 3). We register a package as a list of registry keys (`legs`) when NOTES
names every leg. Twenty-one such packages name Table 6.1 lines, and one names
two measures outside that table. We register the OBR's Table 3.1 tax groups as
the receipts of their lines (`receipts_of`), and every other package in its
producer's words (`words`).

Verdicts:
  ("legs",)                         computed from the legs, as the builder does
                                    for tranche 1's packages
  ("receipts",)                     not_expressible when every leg takes that
                                    verdict, otherwise partial: a run gives
                                    each leg's whole effect, not the producer's
                                    receipts head
  ("words", missing)                partial: the producer lists no set of
                                    registry measures
  ("scope", template, what, regex)  not_expressible, out of the model's scope,
                                    with one of the builder's templates
  ("scope_why", why, regex)         the same, with its own `why`
  ("gap", why, regex, upstream, nearest)
                                    not_expressible, a policyengine-uk
                                    development item
  ("delta", delta, kind, baseline_paths, note)
                                    expressible as a delta on current law
  ("partial", missing, regex)       partial, with its own `missing`
"""

